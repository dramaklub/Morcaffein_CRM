using MigraDoc.DocumentObjectModel;
using MigraDoc.DocumentObjectModel.Tables;
using MigraDoc.Rendering;
using CRM_Morcaffein.Theme;
using MdColor = MigraDoc.DocumentObjectModel.Color;


namespace CRM_Morcaffein.winforms.Services.Reports
{
    /// <summary>
    /// ReportDocument → PDF bytes via MigraDoc. Knows nothing about the domain;
    /// just walks sections and blocks and emits a document.
    /// </summary>
    public static class MigraDocRenderer
    {
        // Brand color for headings and accents (matches BrandPalette.Brand #572400).
        private static readonly MdColor BrandBrown = MdColor.FromRgb(0x57, 0x24, 0x00);
        private static readonly MdColor MutedGrey = MdColor.FromRgb(0x80, 0x80, 0x80);
        private static readonly MdColor RuleGrey = MdColor.FromRgb(0xD0, 0xD0, 0xD0);

        public static byte[] Render(ReportDocument report)
        {
            var doc = new Document();
            doc.Info.Title = report.Title;

            var normal = doc.Styles["Normal"]!;
            normal.Font.Name = "Segoe UI";
            normal.Font.Size = 10;

            var section = doc.AddSection();
            section.PageSetup.PageFormat = PageFormat.A4;
            section.PageSetup.LeftMargin = Unit.FromCentimeter(2);
            section.PageSetup.RightMargin = Unit.FromCentimeter(2);
            section.PageSetup.TopMargin = Unit.FromCentimeter(2);
            section.PageSetup.BottomMargin = Unit.FromCentimeter(2);

            AddHeader(section, report);

            foreach (var s in report.Sections)
                AddSection(section, s);

            var renderer = new PdfDocumentRenderer { Document = doc };
            renderer.RenderDocument();

            using var ms = new MemoryStream();
            renderer.PdfDocument.Save(ms, false);
            return ms.ToArray();
        }

        private static void AddHeader(Section section, ReportDocument report)
        {
            // Title
            var title = section.AddParagraph(report.Title);
            title.Format.Font.Size = 18;
            title.Format.Font.Bold = true;
            title.Format.Font.Color = BrandBrown;
            title.Format.SpaceAfter = Unit.FromPoint(2);

            // Subtitle
            if (!string.IsNullOrWhiteSpace(report.Subtitle))
            {
                var sub = section.AddParagraph(report.Subtitle);
                sub.Format.Font.Size = 11;
                sub.Format.Font.Color = MutedGrey;
                sub.Format.SpaceAfter = Unit.FromPoint(6);
            }

            // Meta line: period · generated by · generated at
            var meta = section.AddParagraph();
            meta.AddText($"Period: {report.PeriodLabel}    ·    ");
            meta.AddText($"Generated by: {report.GeneratedBy}    ·    ");
            meta.AddText($"Generated at: {report.GeneratedAt:yyyy-MM-dd HH:mm}");
            meta.Format.Font.Size = 9;
            meta.Format.Font.Color = MutedGrey;
            meta.Format.SpaceAfter = Unit.FromPoint(4);

            // Thin rule under the header block
            var rule = section.AddParagraph();
            rule.Format.Borders.Bottom.Width = 0.75;
            rule.Format.Borders.Bottom.Color = RuleGrey;
            rule.Format.SpaceAfter = Unit.FromPoint(14);
        }

        private static void AddSection(Section section, ReportSection reportSection)
        {
            var heading = section.AddParagraph(reportSection.Heading);
            heading.Format.Font.Size = 13;
            heading.Format.Font.Bold = true;
            heading.Format.Font.Color = BrandBrown;
            heading.Format.SpaceBefore = Unit.FromPoint(10);
            heading.Format.SpaceAfter = Unit.FromPoint(2);

            if (!string.IsNullOrWhiteSpace(reportSection.Subtitle))
            {
                var sub = section.AddParagraph(reportSection.Subtitle);
                sub.Format.Font.Size = 9;
                sub.Format.Font.Color = MutedGrey;
                sub.Format.SpaceAfter = Unit.FromPoint(6);
            }
            else
            {
                heading.Format.SpaceAfter = Unit.FromPoint(6);
            }

            foreach (var block in reportSection.Blocks)
            {
                switch (block)
                {
                    case MetricStripBlock m: AddMetricStrip(section, m); break;
                    case TableBlock t: AddTable(section, t); break;
                    case ParagraphBlock p: AddParagraph(section, p); break;
                }
            }
        }

        private static void AddMetricStrip(Section section, MetricStripBlock block)
        {
            // One-row 4-column table where each cell is "Label\nValue".
            var table = section.AddTable();
            table.Borders.Width = 0;

            var cols = block.Metrics.Count;
            for (int i = 0; i < cols; i++)
                table.AddColumn(Unit.FromCentimeter(16.0 / Math.Max(1, cols)));

            var row = table.AddRow();
            for (int i = 0; i < cols; i++)
            {
                var (label, value) = block.Metrics[i];
                var cell = row.Cells[i];
                cell.Format.LeftIndent = Unit.FromPoint(0);

                var lbl = cell.AddParagraph(label);
                lbl.Format.Font.Size = 8;
                lbl.Format.Font.Color = MutedGrey;
                lbl.Format.SpaceAfter = Unit.FromPoint(2);

                var val = cell.AddParagraph(value);
                val.Format.Font.Size = 14;
                val.Format.Font.Bold = true;
                val.Format.Font.Color = BrandBrown;
            }

            section.AddParagraph().Format.SpaceAfter = Unit.FromPoint(6);
        }

        private static void AddTable(Section section, TableBlock block)
        {
            if (block.Columns.Count == 0) return;

            var table = section.AddTable();
            table.Borders.Width = 0.5;
            table.Borders.Color = RuleGrey;
            table.Rows.LeftIndent = 0;

            // Column widths — equal-ish, first column wider for labels.
            var total = 16.0;
            var firstCol = block.Columns.Count > 2 ? total * 0.28 : total / block.Columns.Count;
            var rest = block.Columns.Count > 1
                ? (total - firstCol) / (block.Columns.Count - 1)
                : total;

            for (int i = 0; i < block.Columns.Count; i++)
            {
                var w = i == 0 ? firstCol : rest;
                table.AddColumn(Unit.FromCentimeter(w));
            }

            // Header row
            var header = table.AddRow();
            header.HeadingFormat = true;
            header.Format.Font.Bold = true;
            header.Format.Font.Color = BrandBrown;
            header.Shading.Color = MdColor.FromRgb(0xF5, 0xEF, 0xE8);
            for (int i = 0; i < block.Columns.Count; i++)
            {
                var p = header.Cells[i].AddParagraph(block.Columns[i]);
                p.Format.Font.Size = 9;
            }

            // Data rows
            foreach (var r in block.Rows)
            {
                var row = table.AddRow();
                for (int i = 0; i < block.Columns.Count; i++)
                {
                    var txt = i < r.Length ? r[i] : string.Empty;
                    var p = row.Cells[i].AddParagraph(txt);
                    p.Format.Font.Size = 9;
                }
            }

            section.AddParagraph().Format.SpaceAfter = Unit.FromPoint(6);
        }

        private static void AddParagraph(Section section, ParagraphBlock block)
        {
            var p = section.AddParagraph(block.Text);
            p.Format.Font.Size = 9;
            if (block.Muted) p.Format.Font.Color = MutedGrey;
            p.Format.SpaceAfter = Unit.FromPoint(6);
        }
    }
}